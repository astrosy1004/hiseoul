// Builds supabase/seed.sql from src/lib/mock-data.ts so the database starts
// with the same sample data the app shows without Supabase.
// Usage: node --experimental-strip-types scripts/make-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { products, rankings, hotels, sampleOrders } from "../src/lib/mock-data.ts";

const q = (v) => v === undefined || v === null ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v) => v ? `array[${v.map(q).join(",")}]::text[]` : "null";

const out = ["-- Sample data (fictional brands/products). Generated by scripts/make-seed.mjs.", "begin;"];
out.push("insert into public.products (id, category, brand, name, description, store_price_krw, image_url, rating, review_count, skin_types, concerns, routine_step, visible, stock) values");
out.push(products.map((p) => `  (${[q(p.id), q(p.category), j(p.brand), j(p.name), j(p.description), p.storePriceKrw, q(p.imageUrl), p.rating, p.reviewCount, arr(p.skinTypes), arr(p.concerns), q(p.routineStep), p.visible, q(p.stock)].join(", ")})`).join(",\n") + ";");
out.push("insert into public.rankings (region, rank, product_id, change, is_new) values");
out.push(rankings.map((r) => `  (${q(r.region)}, ${r.rank}, ${q(r.productId)}, ${r.change === "new" ? 0 : r.change}, ${r.change === "new"})`).join(",\n") + ";");
out.push("insert into public.hotels (id, name, area) values");
out.push(hotels.map((h) => `  (${q(h.id)}, ${j(h.name)}, ${q(h.area)})`).join(",\n") + ";");
out.push("insert into public.orders (id, created_at, email, guest_name, hotel_id, room, delivery_date, slot, items_krw, service_fee_krw, delivery_fee_krw, total_krw, payment_method, status, notified_status) values"); // sample orders never email anyone
out.push(sampleOrders.map((o) => `  (${[q(o.id), q(o.createdAt), q(o.email), q(o.guestName), q(o.hotelId), q(o.room), "(now() at time zone 'Asia/Seoul')::date", q(o.slot), o.itemsKrw, o.serviceFeeKrw, o.deliveryFeeKrw, o.totalKrw, q(o.paymentMethod), q(o.status), q(o.status)].join(", ")})`).join(",\n") + ";");
out.push("insert into public.order_lines (order_id, product_id, qty, unit_price_krw) values");
out.push(sampleOrders.flatMap((o) => o.lines.map((l) => `  (${q(o.id)}, ${q(l.productId)}, ${l.qty}, ${l.unitPriceKrw})`)).join(",\n") + ";");
out.push("commit;", "");
const seed = out.join("\n");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seed);
// One file to paste into the SQL Editor: schema + sample data.
const schema = readFileSync(new URL("../supabase/schema.sql", import.meta.url), "utf8");
writeFileSync(new URL("../supabase/setup.sql", import.meta.url), schema + "\n\n" + seed);
console.log("wrote supabase/seed.sql and supabase/setup.sql");
